#!/usr/bin/env bash
# ==============================================
# Module: Zsh configuration
# ==============================================

REPO_DIR="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
ZSHRC="$HOME/.zshrc"
ZSH_SRC="$REPO_DIR/zsh"
MARKER="# >>> macbook-setup managed block >>>"
MARKER_END="# <<< macbook-setup managed block <<<"

# Install Oh My Zsh if not present
if [[ ! -d "$HOME/.oh-my-zsh" ]]; then
    log_change "Installing Oh My Zsh"
    sh -c "$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)" "" --unattended
else
    log_skip "Oh My Zsh already installed"
fi

# Ensure .zshrc exists
touch "$ZSHRC"

# Build the managed block from our zsh config files
MANAGED_BLOCK="$MARKER
# Auto-generated by macbook-setup. Do not edit between these markers.
# To customize, edit the source files in $(basename "$REPO_DIR")/zsh/ and rerun setup.

"

# Append each zsh config file
for f in "$ZSH_SRC"/*.zsh; do
    if [[ -f "$f" ]]; then
        MANAGED_BLOCK+="# --- $(basename "$f") ---
"
        MANAGED_BLOCK+="$(cat "$f")
"
    fi
done

MANAGED_BLOCK+="$MARKER_END"

# Check if the managed block already exists and matches
if grep -q "$MARKER" "$ZSHRC" 2>/dev/null; then
    # Extract existing block
    EXISTING=$(sed -n "/$MARKER/,/$MARKER_END/p" "$ZSHRC")

    if [[ "$EXISTING" == "$MANAGED_BLOCK" ]]; then
        log_skip "Zsh config block unchanged"
        return 0 2>/dev/null || exit 0
    fi

    # Replace existing block
    # Create a temp file with the block replaced
    TMPFILE=$(mktemp)
    awk -v marker="$MARKER" -v marker_end="$MARKER_END" -v new_block="$MANAGED_BLOCK" '
        $0 == marker { print new_block; skip=1; next }
        $0 == marker_end { skip=0; next }
        !skip { print }
    ' "$ZSHRC" > "$TMPFILE"
    mv "$TMPFILE" "$ZSHRC"
    log_change "Updated zsh config block in .zshrc"
else
    # Append new block
    echo "" >> "$ZSHRC"
    echo "$MANAGED_BLOCK" >> "$ZSHRC"
    log_change "Added zsh config block to .zshrc"
fi
